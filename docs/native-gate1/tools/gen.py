#!/usr/bin/env python3
"""SplatNative static recompiler driver.

Splits each program NSO (sdk, main) into functions via eh_frame_hdr FDEs,
recompiles each function to C with the capstone-driven emitter, and writes:
  build/gen/<mod>_gen.c   - functions
  build/gen/recomp_meta.c - dispatch switch, reloc patches, init arrays, entry

Game bytes stay on disk (E:\\S3_extract); the runtime loader reads the NSOs
directly. No keys are read here.
"""
import argparse
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "src", "recomp"))

import nso_scan  # noqa: E402  (parsers reused from the module scanner)
from a64 import FnEmitter, Unsupported  # noqa: E402

EXTRACT = r"E:\S3_extract"
BUILD = os.path.join(os.path.dirname(HERE), "build", "gen")
os.makedirs(BUILD, exist_ok=True)

# Absolute load addresses of the S3 v11.2.0 program modules (from NSO headers;
# identical to the addresses Ryujinx logs at boot).
MODULES = ["sdk", "main"]
# Host symbols the game imports that the runtime must provide.
HOST_IMPORTS_PREFIX = ("nvn",)


def load_module(name):
    nso = nso_scan.Nso(os.path.join(EXTRACT, name))
    meta, dyn = nso_scan.parse_mod0_dynamic(nso)
    syms, smeta, err = nso_scan.parse_dynsyms(nso, dyn)
    if err:
        syms = []
    fdes = nso_scan.eh_frame_table(nso, meta)
    return {"name": name, "nso": nso, "meta": meta, "dyn": dyn,
            "syms": syms or [], "fdes": fdes}


def functions_of(mod):
    """FDE ranges clipped to .text, merged/sorted. Returns [(start,end)]."""
    nso = mod["nso"]
    t = nso.segs[0]
    tlo, thi = t["mem_off"], t["mem_off"] + t["size"]
    out = []
    for loc, size in mod["fdes"]:
        s, e = loc, loc + size
        if e <= tlo or s >= thi:
            continue
        out.append((max(s, tlo), min(e, thi)))
    out.sort()
    merged = []
    for s, e in out:
        if merged and s <= merged[-1][1] + 16:
            merged[-1] = (merged[-1][0], max(merged[-1][1], e))
        else:
            merged.append((s, e))
    # drop zero-length / duplicates
    return [(s, e) for s, e in merged if e - s >= 8]


def emit_module(mod, all_mods):
    nso = mod["nso"]
    text = nso.mem[nso.segs[0]["mem_off"]]
    fns = functions_of(mod)
    bodies = []
    gaps = []
    total_bytes = 0
    emitted_bytes = 0
    for s, e in fns:
        em = FnEmitter(s, e)
        body = em.run(text[s - nso.segs[0]["mem_off"]: e - nso.segs[0]["mem_off"]], s)
        total_bytes += (e - s)
        covered = (e - s) - sum(4 for _ in ())
        # coverage = bytes in range minus undef stop (approx: full run, gaps are 4B stops)
        if not em.gaps:
            emitted_bytes += (e - s)
        else:
            emitted_bytes += 0
        bodies.append((s, e, body, em.gaps))
        gaps.extend(em.gaps)
    return {"fns": bodies, "gaps": gaps, "ranges": fns,
            "total_bytes": total_bytes}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true",
                    help="emit only sdk+main but cap functions per module (smoke)")
    args = ap.parse_args()

    mods = [load_module(n) for n in MODULES]
    report = {"modules": {}}

    # symbol resolution maps (absolute addresses, known at gen time)
    sym_addr = {}   # name -> absolute address (from exports with shndx != 0)
    for mod in mods:
        text_base = mod["nso"].segs[0]["mem_off"]
        # NSO dynsym st_value is module-relative (validated: values << image span)
        mod_base = 0
        for s in mod["syms"]:
            if s["name"] and s["shndx"] != 0:
                sym_addr.setdefault(s["name"], text_base + s["value"])

    all_fn_addrs = set()
    for mod in mods:
        print(f"[gen] {mod['name']}: {len(mod['fdes'])} FDEs, "
              f"{len(mod['syms'])} dynsyms ...")
        r = emit_module(mod, mods)
        report["modules"][mod["name"]] = {
            "functions": len(r["ranges"]),
            "text_bytes_in_fns": r["total_bytes"],
            "gap_mnemonics": sorted({g[2] for g in r["gaps"]}),
            "gap_count": len(r["gaps"]),
        }
        all_fn_addrs.update(s for s, e in r["ranges"])

        # ---- write <mod>_gen.c ----
        path = os.path.join(BUILD, f"{mod['name']}_gen.c")
        with open(path, "w") as f:
            f.write(f"/* generated by SplatNative gen.py from {mod['name']} NSO - do not edit */\n")
            f.write('#include "a64_ctx.h"\n')
            f.write("void fn_dispatch(A64Ctx* c);\n\n")
            for s, e, body, gaps in r["fns"]:
                f.write(f"static void fn_{s:x}(A64Ctx* c) {{\n")
                f.write(body)
                f.write("\n}\n\n")
        size = os.path.getsize(path)
        print(f"[gen] wrote {path} ({size} B) gaps={len(r['gaps'])}")
        report["modules"][mod["name"]]["gen_c"] = size
        mod["emit"] = r

    # ---- reloc patches + init arrays + dispatch meta ----
    # Non-host relocations: bake absolute values now (all bases are absolute).
    # Host relocations: patched at load by name (nvnBootstrapLoader, ...).
    patches = []      # (u64 offset, u64 value)
    host_patches = []  # (u64 offset, name)
    RT = 0x403   # R_AARCH64_RELATIVE
    GD = 0x401   # R_AARCH64_GLOB_DAT
    JS = 0x402   # R_AARCH64_JUMP_SLOT
    ABS64 = 0x101
    for mod in mods:
        nso = mod["nso"]
        d = dict(mod["dyn"])
        rela_v = d.get(7)
        relasz = d.get(8, 0)
        jmprel_v = d.get(20) or None
        pltrelsz = d.get(20, 0)
        # DT_PLTRELSZ=20, DT_JMPREL=23
        jmprel_v = d.get(23)
        pltrelsz = d.get(20, 0)
        relas = []
        if rela_v:
            off = nso.v2file(rela_v)
            if off is not None:
                for o in range(off, off + relasz, 24):
                    r_off, r_info, r_add = struct.unpack_from("<QQq", nso.image, o)
                    relas.append((r_off, r_info, r_add))
        if jmprel_v and pltrelsz:
            off = nso.v2file(jmprel_v)
            if off is not None:
                for o in range(off, off + pltrelsz, 24):
                    r_off, r_info, r_add = struct.unpack_from("<QQq", nso.image, o)
                    relas.append((r_off, r_info, r_add))
        text_base = nso.segs[0]["mem_off"]
        n_host = n_local = n_rel = 0
        for r_off, r_info, r_add in relas:
            typ = r_info & 0xFFFFFFFF
            symi = r_info >> 32
            if typ == RT:
                patches.append((r_off, (text_base + r_add) & 0xFFFFFFFFFFFFFFFF))
                n_rel += 1
                continue
            if typ not in (GD, JS, ABS64):
                continue
            s = mod["syms"][symi] if symi < len(mod["syms"]) else None
            name = s["name"] if s else None
            if not name:
                # local undefined -> resolve via shndx
                patches.append((r_off, 0))
                n_local += 1
                continue
            if s["shndx"] != 0:
                patches.append((r_off, text_base + s["value"]))
                n_local += 1
            elif name in sym_addr:
                patches.append((r_off, sym_addr[name]))
                n_local += 1
            else:
                host_patches.append((r_off, name))
                n_host += 1
        report["modules"][mod["name"]]["relocs"] = {
            "total": len(relas), "baked": n_rel + n_local, "host": n_host}
        mod["host_patches"] = host_patches
        mod["init_array"] = []
        if 25 in d:
            ia = nso.v2file(d[25])
            iasz = d.get(27, 0)
            if ia is not None:
                for o in range(ia, ia + iasz, 8):
                    v = struct.unpack_from("<Q", nso.image, o)[0]
                    if v:
                        mod["init_array"].append(v)

    # entry point: prefer exported nnMain
    entry = sym_addr.get("nnMain")
    report["entry_nnMain"] = hex(entry) if entry else None
    # nnMain's st_value is text_base + value already in sym_addr

    # unresolved host symbol names (unique)
    host_names = sorted({n for _, n in host_patches})
    report["host_symbols"] = host_names

    # ---- recomp_meta.c ----
    path = os.path.join(BUILD, "recomp_meta.c")
    with open(path, "w") as f:
        f.write("/* generated - dispatch + load metadata */\n")
        f.write('#include "a64_ctx.h"\n\n')
        for mod in mods:
            f.write(f"extern const uint8_t* {mod['name']}_text_ptr;\n")
        f.write("\nvoid fn_dispatch(A64Ctx* c) {\n    switch (c->pc) {\n")
        for addr in sorted(all_fn_addrs):
            f.write(f"    case {addr:#x}ull: fn_{addr:x}(c); return;\n")
        f.write("    default: a64_unmapped(c); return;\n    }\n}\n\n")
        # load metadata
        f.write("const RecPatch g_patches[] = {\n")
        for off, val in patches:
            f.write(f"    {{ {off:#x}ull, {val:#x}ull, 0 }},\n")
        f.write("};\n")
        f.write(f"const unsigned g_patch_count = {len(patches)};\n\n")
        f.write("const HostPatch g_host_patches[] = {\n")
        for mod in mods:
            for off, name in mod["host_patches"]:
                f.write(f"    {{ {off:#x}ull, {c_str(name)} }},\n")
        f.write("};\n")
        f.write(f"const unsigned g_host_patch_count = {sum(len(m['host_patches']) for m in mods)};\n\n")
        f.write("const unsigned long long g_init_arrays[][2] = {\n")
        for mod in mods:
            f.write(f"    /* {mod['name']} */\n")
            for a in mod["init_array"]:
                f.write(f"    {{ 1, {a:#x}ull }},\n")
        f.write("    { 0, 0 }\n};\n")
        if entry:
            f.write(f"const unsigned long long g_entry = {entry:#x}ull;\n")
        else:
            f.write("const unsigned long long g_entry = 0;\n")

    size = os.path.getsize(path)
    print(f"[gen] wrote {path} ({size} B) patches={len(patches)} host={len(host_patches)}")
    report["meta_c"] = size

    rpath = os.path.join(BUILD, "gen_report.json")
    with open(rpath, "w") as f:
        json.dump(report, f, indent=1)
    print(f"[gen] report: {rpath}")
    for mn, info in report["modules"].items():
        print(f"  {mn}: fns={info['functions']} gaps={info['gap_count']} "
              f"gap_mnemonics={info['gap_mnemonics'][:20]}")


if __name__ == "__main__":
    main()
